bazel_refresh_index() {
  [ -n "$XC_BAZEL_TARGET" ] || die "No Bazel target selected."
  local ver="$SKBSP_VERSION" cache="$STATE/skbsp-$SKBSP_VERSION" mark="$ROOT/.bsp/.vscode-xcode-setup"
  local base="https://github.com/spotify/sourcekit-bazel-bsp/releases/download/$ver" bin tpl tpl_bsp script
  if [ -f "$ROOT/.bsp/skbsp.json" ] && [ ! -f "$mark" ]; then
    ok "Code completion: .bsp/skbsp.json is already set up by your project (setup_sourcekit_bsp); leaving it as is."
    return 0
  fi
  if [ ! -f "$cache/ok" ]; then
    info "Downloading sourcekit-bazel-bsp $ver (Bazel build server for code completion)..."
    rm -rf "$cache"; mkdir -p "$cache/bin" "$cache/src"
    if ! { curl -fsSL -o "$cache/bin.zip" "$base/sourcekit-bazel-bsp-$ver-darwin.zip" \
          && curl -fsSL -o "$cache/src.tar.gz" "$base/release.tar.gz" \
          && unzip -q -o "$cache/bin.zip" -d "$cache/bin" && tar -xzf "$cache/src.tar.gz" -C "$cache/src"; }; then
      warn "Couldn't download sourcekit-bazel-bsp; code completion won't know about Bazel targets. Retry with 'Xcode: Refresh Code Completion'."
      return 0
    fi
    touch "$cache/ok"
  fi
  bin="$(find "$cache/bin" -name sourcekit-bazel-bsp -type f | head -n 1)"
  tpl="$(find "$cache/src" -name setup_sourcekit_bsp.sh.tpl | head -n 1)"
  tpl_bsp="$(find "$cache/src" -name bsp_config.json.tpl | head -n 1)"
  if [ -z "$bin" ] || [ -z "$tpl" ] || [ -z "$tpl_bsp" ]; then
    warn "The sourcekit-bazel-bsp $ver download looks different than expected; skipping code completion setup."
    return 0
  fi
  chmod +x "$bin"
  bazel_flags
  python3 -I -c "$PY_SKBSP" "$tpl_bsp" "$cache/skbsp.json" "$cache/config.json" "$(bazel_bin)" "$XC_BAZEL_TARGET" \
    "**/*.swift,**/*.h,**/*.m,**/*.mm,**/*.c,**/*.cpp" "${BFLAGS[@]}" \
    --features=swift.index_while_building --experimental_convenience_symlinks=ignore --color=no --curses=no \
    || { warn "Couldn't write the sourcekit-bazel-bsp config."; return 0; }
  script="$cache/setup.sh"
  sed -e "s|%sourcekit_bazel_bsp_path%|$bin|g" -e "s|%bsp_config_path%|$cache/skbsp.json|g" \
      -e "s|%lsp_config_path%|$cache/config.json|g" -e "s|%merge_lsp_config_env%|1|g" \
      -e "s|%bazel_wrapper%|$(bazel_bin)|g" -e "s|%no_extra_output_base_env%||g" "$tpl" > "$script"
  if BUILD_WORKSPACE_DIRECTORY="$ROOT" /bin/bash "$script" > "$STATE/skbsp-setup.log" 2>&1; then
    touch "$mark"
    ok "Code completion set up for $XC_BAZEL_TARGET (sourcekit-bazel-bsp). Run 'Swift: Restart LSP Server' if VS Code was already open."
  else
    warn "sourcekit-bazel-bsp setup failed; see $STATE/skbsp-setup.log"
  fi
}

