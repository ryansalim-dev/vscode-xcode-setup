# Picks the app target from `xcodebuild -showBuildSettings -json` and prints shell assignments.
PY_PICK='
import json, shlex, sys
want = sys.argv[1] if len(sys.argv) > 1 else ""
try:
    data = json.load(sys.stdin)
except ValueError:
    sys.exit(1)
if not data:
    sys.exit(1)
def matches(t):
    if want:
        return t.get("target") == want
    return t.get("buildSettings", {}).get("WRAPPER_EXTENSION") == "app"
pick = next((t for t in data if matches(t)), data[0])
s = pick.get("buildSettings", {})
d = s.get("TARGET_BUILD_DIR", "")
vals = {
    "APP_PATH": d + "/" + s.get("FULL_PRODUCT_NAME", ""),
    "EXEC_PATH": d + "/" + s.get("EXECUTABLE_PATH", ""),
    "BUNDLE_ID": s.get("PRODUCT_BUNDLE_IDENTIFIER", ""),
    "PRODUCT_NAME": s.get("FULL_PRODUCT_NAME", ""),
    "TARGET_NAME": pick.get("target", ""),
    "SUPPORTED_PLATFORMS": s.get("SUPPORTED_PLATFORMS", ""),
    # Projects generated by rules_xcodeproj point the debugger at an lldbinit (working directory and
    # source maps for Bazel-built code). Xcode writes it in a Run pre-action, so keep what is needed
    # to write it ourselves.
    "LLDB_INIT": s.get("BAZEL_LLDB_INIT", ""),
    "LLDB_INIT_CMD": "",
}
script = s.get("BAZEL_INTEGRATION_DIR", "") + "/create_lldbinit.sh"
if vals["LLDB_INIT"] and s.get("BAZEL_INTEGRATION_DIR"):
    keys = ["PROJECT_DIR", "BAZEL_OUT", "BAZEL_EXTERNAL", "OBJROOT", "CONFIGURATION", "BAZEL_LLDB_INIT",
            "RESOLVED_REPOSITORIES", "BAZEL_SEPARATE_INDEXBUILD_OUTPUT_BASE"]
    vals["LLDB_INIT_CMD"] = " ".join(["env"] + ["%s=%s" % (k, shlex.quote(s.get(k, ""))) for k in keys]
                                     + ["/bin/bash", shlex.quote(script)])
for k in sorted(vals):
    print("%s=%s" % (k, shlex.quote(vals[k])))
'

