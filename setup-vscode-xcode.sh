APP_KINDS='kind("(ios|macos|tvos|watchos|visionos)_application", //...)'

bazel_select_target() {
  local force=0 out kind rule label i def=0 found=0 want old_platform err
  [ "${1:-}" = "--prompt" ] && force=1
  info "Finding app targets (bazel query)..."
  err="$STATE/query.err"
  out="$(bazel_cmd query --keep_going --noshow_progress "$APP_KINDS" --output=label_kind 2>"$err")" || true
  local labels=() kinds=()
  while read -r kind rule label; do
    [ "$rule" = rule ] && [ -n "$label" ] && { labels+=("$label"); kinds+=("$kind"); }
  done <<< "$out"
  [ ${#labels[@]} -gt 0 ] || die "No ios_application/macos_application/... targets found. bazel said: $(tail -n 15 "$err")"
  want="${XC_PREF_TARGET:-$XC_BAZEL_TARGET}"
  if [ -n "$want" ]; then
    case "$want" in //*|@*) ;; *) want="//$want" ;; esac
    for i in "${!labels[@]}"; do
      if [ "${labels[$i]}" = "$want" ] || [ "${labels[$i]}" = "$want:${want##*/}" ]; then def=$i; found=1; fi
    done
    [ "$found" = 1 ] || warn "Bazel target '$want' not found (or it isn't an *_application)."
  fi
  if [ ${#labels[@]} -gt 1 ] && interactive && { [ "$force" = 1 ] || [ "$found" = 0 ]; }; then
    local items=()
    for i in "${!labels[@]}"; do items+=("${labels[$i]}  (${kinds[$i]})"); done
    choose "$def" "Which app should VS Code build?" "${items[@]}"
    def=$CHOICE
  fi
  XC_BAZEL_TARGET="${labels[$def]}"
  old_platform="$XC_PLATFORM"
  XC_PLATFORM="${kinds[$def]%%_*}"
  ok "Bazel target: $XC_BAZEL_TARGET (${kinds[$def]})"
  [ "$old_platform" = "$XC_PLATFORM" ] || { XC_SIM_UDID=""; XC_SIM_NAME=""; }
  save_config
  if is_sim && [ -z "$XC_SIM_UDID" ]; then cmd_select_sim; fi
  bazel_refresh_index
}

