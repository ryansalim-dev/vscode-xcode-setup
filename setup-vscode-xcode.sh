# ── Bazel (rules_apple) ────────────────────────────────────────────────────────
# With XC_BUILD_SYSTEM=bazel, the app is built with `bazel build` directly (no .xcodeproj),
# then the .ipa/.zip is unpacked into .vscode/xcode/.state/app and installed like any other app.

bazel_bin() {
  if command -v bazel >/dev/null 2>&1; then echo bazel
  elif command -v bazelisk >/dev/null 2>&1; then echo bazelisk
  else die "Bazel isn't installed. Install it with: brew install bazelisk"
  fi
}
# UI flags only: they don't change Bazel's analysis cache. Plain output keeps the Problems matcher happy.
bazel_cmd() { local sub="$1"; shift; "$(bazel_bin)" "$sub" --color=no --curses=no "$@"; }

bazel_mode() {
  case "$XC_CONFIGURATION" in
    Release|release|opt) echo opt ;;
    fastbuild) echo fastbuild ;;
    *) echo dbg ;;
  esac
}

# Sets BFLAGS: compilation mode plus the CPU flags that make rules_apple build for the simulator.
bazel_flags() {
  local arch sim
  arch="$(uname -m)"
  if [ "$arch" = arm64 ]; then sim=sim_arm64; else arch=x86_64; sim=x86_64; fi
  BFLAGS=("--compilation_mode=$(bazel_mode)")
  case "$XC_PLATFORM" in
    ios) BFLAGS+=("--ios_multi_cpus=$sim") ;;
    tvos) BFLAGS+=("--tvos_cpus=$sim") ;;
    watchos) BFLAGS+=("--watchos_cpus=$arch") ;;
    visionos) BFLAGS+=("--visionos_cpus=sim_arm64") ;;
    macos) BFLAGS+=("--macos_cpus=$arch") ;;
  esac
  # shellcheck disable=SC2206  # XC_BAZEL_ARGS is a space-separated flag list
  [ -z "$XC_BAZEL_ARGS" ] || BFLAGS+=($XC_BAZEL_ARGS)
}

bazel_args() {
  [ -n "$XC_BAZEL_TARGET" ] || die "No Bazel target selected. Run the task 'Xcode: Select Bazel Target'."
  [ -n "$XC_PLATFORM" ] || bazel_select_target
  ensure_sim
  bazel_flags
  BARGS=("$XC_BAZEL_TARGET")
}

# Caches `bazel info` paths the debugger needs (they only change if the output base moves).
bazel_info() {
  local cache="$STATE/bazel-info.env" ws
  if [ -f "$cache" ]; then
    # shellcheck source=/dev/null
    . "$cache"
    [ "${BZ_ROOT:-}" = "$ROOT" ] && [ -d "${BZ_EXECROOT:-/nonexistent}" ] && return 0
  fi
  ws="$(bazel_cmd info --noshow_progress execution_root output_base 2>/dev/null)" || die "bazel info failed."
  BZ_EXECROOT="$(printf '%s\n' "$ws" | sed -n 's/^execution_root: //p')"
  BZ_OUTPUT_BASE="$(printf '%s\n' "$ws" | sed -n 's/^output_base: //p')"
  BZ_ROOT="$ROOT"
  printf 'BZ_EXECROOT=%q\nBZ_OUTPUT_BASE=%q\nBZ_ROOT=%q\n' "$BZ_EXECROOT" "$BZ_OUTPUT_BASE" "$BZ_ROOT" > "$cache"
}

plist_get() { plutil -extract "$2" raw -o - "$1" 2>/dev/null; }

# Finds the target's .ipa/.zip/.app, unpacks it into $STATE/app and sets APP_PATH, EXEC_PATH, BUNDLE_ID...
bazel_stage_app() {
  local out f line stamp plist exe
  out="$(bazel_cmd cquery --noshow_progress "${BFLAGS[@]}" --output=files "$XC_BAZEL_TARGET" 2>"$STATE/cquery.err")" \
    || die "bazel cquery failed: $(tail -n 20 "$STATE/cquery.err")"
  f=""
  while IFS= read -r line; do
    case "$line" in *.ipa|*.app|*.zip) f="$line"; break ;; esac
  done <<< "$out"
  [ -n "$f" ] || die "$XC_BAZEL_TARGET doesn't produce an .ipa, .zip or .app (outputs: $out). Is it an *_application target?"
  case "$f" in /*) ;; *) bazel_info; f="$BZ_EXECROOT/$f" ;; esac
  [ -e "$f" ] || die "$f doesn't exist yet. Build first (Shift+Cmd+B)."
  if [ -d "$f" ]; then
    APP_PATH="$f"
  else
    stamp="$f $(stat -f '%m %z' "$f" 2>/dev/null || stat -c '%Y %s' "$f")"
    if [ "$(cat "$STATE/app.stamp" 2>/dev/null)" != "$stamp" ] || [ -z "$(find "$STATE/app" -maxdepth 2 -name '*.app' -type d 2>/dev/null)" ]; then
      rm -rf "$STATE/app"
      mkdir -p "$STATE/app"
      unzip -q -o "$f" -d "$STATE/app" || die "Couldn't unpack $f."
      chmod -R u+w "$STATE/app"
      printf '%s' "$stamp" > "$STATE/app.stamp"
    fi
    APP_PATH="$(find "$STATE/app" -maxdepth 2 -name '*.app' -type d | head -n 1)"
    [ -n "$APP_PATH" ] || die "No .app inside $f."
  fi
  if [ -f "$APP_PATH/Contents/Info.plist" ]; then
    plist="$APP_PATH/Contents/Info.plist"; exe="$(plist_get "$plist" CFBundleExecutable)"
    EXEC_PATH="$APP_PATH/Contents/MacOS/$exe"
  else
    plist="$APP_PATH/Info.plist"; exe="$(plist_get "$plist" CFBundleExecutable)"
    EXEC_PATH="$APP_PATH/$exe"
  fi
  BUNDLE_ID="$(plist_get "$plist" CFBundleIdentifier)"
  PRODUCT_NAME="$(basename "$APP_PATH")"
  # shellcheck disable=SC2034  # written out via ${!v}
  TARGET_NAME="$XC_BAZEL_TARGET"
  [ -n "$exe" ] && [ -n "$BUNDLE_ID" ] || die "Couldn't read CFBundleExecutable/CFBundleIdentifier from $plist."
  {
    echo "# bazel|$XC_BAZEL_TARGET|${BFLAGS[*]}"
    for v in APP_PATH EXEC_PATH BUNDLE_ID PRODUCT_NAME TARGET_NAME; do printf '%s=%q\n' "$v" "${!v}"; done
  } > "$STATE/settings.env"
}

bazel_load_settings() {
  local cache="$STATE/settings.env"
  if [ -f "$cache" ] && [ "$(head -n 1 "$cache")" = "# bazel|$XC_BAZEL_TARGET|${BFLAGS[*]}" ]; then
    # shellcheck source=/dev/null
    . "$cache"
    return 0
  fi
  bazel_stage_app
}

bazel_build() {
  bazel_args
  info "Building ${B}$XC_BAZEL_TARGET${N} with Bazel (-c $(bazel_mode)) for $(dest_label)..."
  local t0=$SECONDS
  if bazel_cmd build "${BFLAGS[@]}" "$XC_BAZEL_TARGET" 2>&1; then
    bazel_stage_app
    ok "Build succeeded in $((SECONDS - t0))s."
  else
    die "Build failed. Errors are listed in the Problems panel (Shift+Cmd+M)."
  fi
}

