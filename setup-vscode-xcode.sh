def strip_jsonc(text):
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_str = False
            i += 1
            continue
        if c == '"':
            in_str = True
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        out.append(c)
        i += 1
    return re.sub(r",(\s*[}\]])", r"\1", "".join(out))


def load(name):
    path = os.path.join(VS, name)
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as f:
        raw = f.read()
    if not raw.startswith(MARK):
        bak = path + ".before-xcode-setup"
        if not os.path.exists(bak):
            shutil.copyfile(path, bak)
            print("  Saved a copy of your original %s as %s" % (path, bak))
    if not raw.strip():
        return {}
    try:
        data = json.loads(strip_jsonc(raw))
        return data if isinstance(data, dict) else {}
    except ValueError:
        bak = path + ".unparseable-" + time.strftime("%Y%m%d-%H%M%S")
        shutil.copyfile(path, bak)
        print("  Couldn't parse %s, so it was rebuilt (old copy: %s)" % (path, bak))
        return {}


def save(name, obj, note):
    path = os.path.join(VS, name)
    with open(path, "w", encoding="utf-8") as f:
        f.write("%s. %s\n" % (MARK, note))
        json.dump(obj, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print("  Wrote %s" % path)


